"""Regenerate app/spoor/figures/fontmetrics.py from the bundled Atkinson Hyperlegible fonts.

Developer tool, not needed to run Spoor. The figures measure every label with these advance widths so
text is placed and truncated deterministically, without a font library at run time.

usage:  pip install fonttools brotli && python build/make_fontmetrics.py

Characters the bundled fonts do not cover (Cyrillic, Greek, CJK, ...) are drawn by the viewer's
fallback font; for those the generated table holds DejaVu Sans widths, which are wider than common
system fonts (Segoe UI, Arial), so the estimate errs on the side of more room."""
from __future__ import annotations

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "app" / "spoor" / "web" / "static" / "fonts"
OUT = ROOT / "app" / "spoor" / "figures" / "fontmetrics.py"
FACES = {
    "NEXT_400": ["atkinson-hyperlegible-next-latin-400-normal.woff2", "atkinson-hyperlegible-next-latin-ext-400-normal.woff2"],
    "NEXT_700": ["atkinson-hyperlegible-next-latin-700-normal.woff2", "atkinson-hyperlegible-next-latin-ext-700-normal.woff2"],
    "MONO_400": ["atkinson-hyperlegible-mono-latin-400-normal.woff2", "atkinson-hyperlegible-mono-latin-ext-400-normal.woff2"],
}
FALLBACK_FONT = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
FALLBACK_BLOCKS = [(0x0370, 0x03FF), (0x0400, 0x052F), (0x0530, 0x058F), (0x0590, 0x05FF), (0x10A0, 0x10FF),
                   (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F), (0x2190, 0x21FF),
                   (0x2200, 0x22FF), (0x2500, 0x257F), (0x25A0, 0x25FF)]


def advances(font: TTFont) -> dict[int, int]:
    upm = font["head"].unitsPerEm
    hm = font["hmtx"].metrics
    return {cp: round(hm[g][0] * 1000 / upm) for cp, g in font.getBestCmap().items() if cp >= 0x20}


def extents(font: TTFont) -> tuple[int, int]:
    glyf = font["glyf"]
    upm = font["head"].unitsPerEm
    hi, lo = 0, 0
    for cp, g in font.getBestCmap().items():
        if cp < 0x20:
            continue
        gl = glyf[g]
        if gl.numberOfContours == 0:
            continue
        gl.recalcBounds(glyf)
        hi, lo = max(hi, gl.yMax), min(lo, gl.yMin)
    return round(hi * 1000 / upm), round(lo * 1000 / upm)


def fmt_table(name: str, table: dict[int, int]) -> str:
    items = sorted(table.items())
    lines, cur = [], ""
    for cp, w in items:
        tok = f"{cp}:{w},"
        if len(cur) + len(tok) > 110:
            lines.append(cur)
            cur = ""
        cur += tok
    lines.append(cur)
    return f"{name} = {{\n" + "\n".join("    " + l for l in lines) + "\n}\n"


def main() -> None:
    out = ['"""Advance widths (1/1000 em) of the fonts the figures embed. Generated by build/make_fontmetrics.py - do not edit."""',
           ""]
    top, bottom = 0, 0
    for name, files in FACES.items():
        table: dict[int, int] = {}
        for fn in files:
            f = TTFont(FONTS / fn)
            for cp, w in advances(f).items():
                if cp in table and table[cp] != w:
                    sys.exit(f"{name}: width of U+{cp:04X} differs between subsets")
                table[cp] = w
            hi, lo = extents(f)
            top, bottom = max(top, hi), min(bottom, lo)
        out.append(fmt_table(name, table))
    out.append(f"INK_TOP = {top}       # highest point of any glyph above the baseline")
    out.append(f"INK_BOTTOM = {bottom}  # lowest point below the baseline (negative)")
    out.append("")
    fb: dict[int, int] = {}
    if FALLBACK_FONT.exists():
        f = TTFont(FALLBACK_FONT)
        adv = advances(f)
        for lo, hi in FALLBACK_BLOCKS:
            for cp in range(lo, hi + 1):
                if cp in adv and adv[cp] > 0:
                    fb[cp] = adv[cp]
    else:
        print(f"warning: {FALLBACK_FONT} not found; fallback widths use the default only")
    out.append("# DejaVu Sans widths for characters outside the bundled fonts (an upper bound for common system fonts)")
    out.append(fmt_table("FALLBACK", fb))
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
